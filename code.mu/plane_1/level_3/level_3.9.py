# Task 3 - Даны два списка: lst1 = [1, 2, 3] lst2 = [4, 5, 6]. 
# Переберите эти списки одним циклом и в каждой итерации выводите 
# их элементы следующим образом: '1,4' '2,5' '3,6'
lst1 = [1, 2, 3]
lst2 = [4, 5, 6]
