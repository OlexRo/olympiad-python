# Task 1 -  Дан список с числами. 
# Удалите из него числа, имеющие два и более нуля.
numbers = [1, 20, 3, 400, 5]
print([x for x in numbers if '0' not in str(x)])

# Task 2 - Найдите все числа от 1 до 1000, 
# сумма цифр которых равна 13. Результат запишите в сет.
my_set = set()
for x in range(1, 1001):
  numbers = 0
  for c in str(x):
    numbers += int(c)
    if numbers == 13:
      my_set.add(x)
print(my_set)

