# Task 4 - Дан следующий словарь. Найдите сумму элементов этого словаря.
dct = {
	1: {
		1: 11,
		2: 12,
		3: 13,
	},
	2: {
		1: 21,
		2: 22,
		3: 23,
	},
	3: {
		1: 24,
		2: 25,
		3: 26,
	},
}
total = 0
for value1 in dct.values():
  for value2 in value1.values():
    total += value2
print(total)