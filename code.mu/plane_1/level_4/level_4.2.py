# Task 1 - Дано число. Получите список делителей этого числа.
number1 = 12
print([i for i in range(1, number1 + 1) if number1 % i == 0])

# Task 2 - Выведите в консоль все числа в промежутке от 10 до 1000, 
# у которых первая цифра четная.
print([x for x in range(10, 1001) if int(str(x)[0]) % 2 == 0])

# Task 3 - Дан список: [[1, 2, 3], [4, 5, 6],[7, 8, 9],].
